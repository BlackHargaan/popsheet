import { expect, test } from '@playwright/test'
import type { Page, Locator } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function sample(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Try the sample quiz' }).click()
  await expect(page.getByRole('button', { name: 'Select', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.page svg .q')).toHaveCount(10)
}
const rect = (page: Page, n: number) => page.locator('.page svg .q > .q-box').nth(n)
async function position(locator: Locator) { return { x: Number(await locator.getAttribute('x')), y: Number(await locator.getAttribute('y')) } }

test('selection, nudging, group dragging, undo/redo and deletion', async ({ page }) => {
  await sample(page)
  const before = await position(rect(page, 0))
  await rect(page, 0).click({ position: { x: 2, y: 2 } })
  await page.keyboard.press('ArrowRight')
  expect((await position(rect(page, 0))).x).toBe(before.x + 1)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect(await position(rect(page, 0))).toEqual(before)
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  expect((await position(rect(page, 0))).x).toBe(before.x + 1)
  await rect(page, 1).click({ modifiers: ['Shift'], position: { x: 2, y: 2 } })
  await expect(page.getByText('2 selected', { exact: true })).toBeVisible()
  const groupBefore = await Promise.all([position(rect(page, 0)), position(rect(page, 1))])
  await rect(page, 0).scrollIntoViewIfNeeded()
  const box = (await rect(page, 0).boundingBox())!
  await page.mouse.move(box.x + 5, box.y + 5); await page.mouse.down()
  await page.keyboard.down('Alt'); await page.mouse.move(box.x + 25, box.y + 25, { steps: 8 }); await page.mouse.up(); await page.keyboard.up('Alt')
  const after = await Promise.all([position(rect(page, 0)), position(rect(page, 1))])
  expect(after[0].x).toBeGreaterThan(groupBefore[0].x)
  expect(after[1].x - groupBefore[1].x).toBeCloseTo(after[0].x - groupBefore[0].x)
  await page.keyboard.press('Control+z')
  expect(await position(rect(page, 0))).toEqual(groupBefore[0])
  expect(await position(rect(page, 1))).toEqual(groupBefore[1])
  await page.keyboard.press('Delete')
  await expect(page.locator('.page svg .q')).toHaveCount(8)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.page svg .q')).toHaveCount(10)
})

test('select does not add questions; align and cancelled drag are reversible', async ({ page }) => {
  await sample(page)
  await page.locator('.add-layer').click({ position: { x: 200, y: 200 } })
  await expect(page.locator('.page svg .q')).toHaveCount(10)
  await rect(page, 0).click({ position: { x: 2, y: 2 } }); await page.keyboard.press('Shift+ArrowRight')
  await rect(page, 1).click({ modifiers: ['Shift'], position: { x: 2, y: 2 } })
  const before = await position(rect(page, 1))
  await page.getByRole('button', { name: 'Align left' }).click()
  expect((await position(rect(page, 1))).x).toBe((await position(rect(page, 0))).x)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect(await position(rect(page, 1))).toEqual(before)
  await rect(page, 0).scrollIntoViewIfNeeded()
  const original = await position(rect(page, 0)), box = (await rect(page, 0).boundingBox())!
  await page.mouse.move(box.x + 5, box.y + 5); await page.mouse.down(); await page.mouse.move(box.x + 45, box.y + 25)
  await page.keyboard.press('Escape'); await page.mouse.up()
  expect(await position(rect(page, 0))).toEqual(original)
})

test('backup download and restore preserve PDFs; preview and conflict skip work', async ({ page }) => {
  await sample(page)
  await page.getByRole('link', { name: 'All worksheets' }).click()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download backup' }).click()
  const download = await downloaded
  const content = await readFile((await download.path())!)
  expect(JSON.parse(content.toString()).format).toBe('popsheet-backup')
  const input = page.locator('input[accept="application/json,.json"]')
  await input.setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: content })
  await expect(page.getByText(/Ready to restore 1 worksheets/)).toBeVisible()
  await page.getByRole('button', { name: 'Restore now' }).click()
  await expect(page.getByRole('status')).toContainText('Restored 0 records')
  // Remove the worksheet, then recover it from the downloaded file.
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: /Delete / }).click()
  await expect(page.locator('.sheet')).toHaveCount(0)
  await input.setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: content })
  await page.getByRole('button', { name: 'Restore now' }).click()
  await expect(page.locator('.sheet')).toHaveCount(1)
  await page.locator('.sheet-title').click()
  await expect(page.locator('.page svg .q')).toHaveCount(10)
  await expect(page.locator('.page-bg canvas')).toBeVisible()
})

test('new questions, answer edits and page-code moves each undo in one step', async ({ page }) => {
  await sample(page)
  await page.getByRole('button', { name: 'Bubbles', exact: true }).click()
  await page.locator('.add-layer').click({ position: { x: 150, y: 200 } })
  await expect(page.locator('.page svg .q')).toHaveCount(11)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.page svg .q')).toHaveCount(10)
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.locator('.page svg .q')).toHaveCount(11)
  const answer = page.getByRole('button', { name: 'Question 11 answer A', exact: true })
  await answer.click()
  await expect(answer).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(answer).toHaveAttribute('aria-pressed', 'false')
  const code = page.locator('.page-code rect').first()
  const before = await position(code)
  await code.scrollIntoViewIfNeeded()
  const box = (await code.boundingBox())!
  await page.mouse.move(box.x + 10, box.y + 10); await page.mouse.down()
  await page.mouse.move(box.x - 40, box.y + 80, { steps: 8 }); await page.mouse.up()
  expect(await position(code)).not.toEqual(before)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect(await position(code)).toEqual(before)
  await page.reload()
  await expect(page.locator('.page-code')).toBeVisible()
  expect(await position(code)).toEqual(before)
})

